package org.arkikeskus.launcher.feature.settings

import android.net.Uri

/**
 * Everything the Settings page can ask for: one function per setting it changes and per thing it
 * creates or removes. The view model is the one implementation; the page's rows call these and
 * nothing else, so what a row does is the same wherever the row is shown.
 */
internal interface SettingsActions {
    fun importDrawerWallpaper(uri: Uri)
    fun clearDrawerWallpaper()
    fun setAppHidden(key: String, hidden: Boolean)
    fun createDrawerFolder(name: String)
    fun renameDrawerFolder(id: Long, name: String)
    fun deleteDrawerFolder(id: Long)
    fun setAppInDrawerFolder(id: Long, key: String, member: Boolean)
    fun setSwipeUp(value: Boolean)
    fun setSwipeDown(value: Boolean)
    fun setFolderSwipeOpensFirstApp(value: Boolean)
    fun setHideHomeAppsFromDrawer(value: Boolean)
    fun setWidgetEdgesAlignWithIcons(value: Boolean)
    fun setDockEnabled(value: Boolean)
    fun setDockColumns(value: Int)
    fun setDrawerColumns(value: Int)
    fun setShowDrawerSearch(value: Boolean)
    fun setShowFrequentApps(value: Boolean)
    fun setDrawerOpensAtTop(value: Boolean)
    fun setSortDrawerFolders(value: Boolean)
    fun setMixDrawerFolders(value: Boolean)
    fun setBlurBehindDrawer(value: Boolean)
    fun setDrawerBlurStrength(value: Float)
    fun setDrawerBackgroundColor(argb: Int?)
    fun setDrawerLabelColor(argb: Int?)
    fun setDrawerPictureDim(value: Float)
    fun setFontFamily(font: String)
    fun setThemeAllIcons(value: Boolean)
    fun setFolderColumns(value: Int)
    fun setSectionCollapsed(id: String, collapsed: Boolean)
    fun setHomeColumns(value: Int)
    fun setHomeRows(value: Int)
    fun setShowDockLabels(value: Boolean)
    fun setShowHomeLabels(value: Boolean)
    fun setShowDrawerLabels(value: Boolean)
    fun setShowHomeFolderNames(value: Boolean)
    fun setShowDrawerFolderNames(value: Boolean)
    fun setDockBackgroundOpacity(value: Float)
    fun setDockBottomSpacing(value: Int)
    fun setDrawerBackgroundOpacity(value: Float)
    fun setShowPageIndicator(value: Boolean)
    fun setHomePageMarker(value: String)
    fun setInfiniteScroll(value: Boolean)
    fun setShowNotificationDots(value: Boolean)
    fun setNotificationDotCount(value: Boolean)
    fun setNotificationDotScale(value: Float)
    fun setUseThemedIcons(value: Boolean)
    fun setIconPack(pkg: String)
    fun setSearchContacts(value: Boolean)
    fun setLeftSwipeAppKey(key: String?)
    fun setWeatherAppKey(key: String?)
    fun setPageSwitchSpeed(speed: String)
    fun setDesktopLocked(value: Boolean)
    fun setDoubleTapToLock(value: Boolean)
    fun setLockSoundsEnabled(value: Boolean)
    fun setLockSound(slot: SoundSlot, uri: String)
    fun setLongPressScale(value: Float)
    fun setIconSwipeDistance(value: Float)
    fun setAppLabelTextScale(value: Float)
    fun setIconScale(value: Float)
    fun setDrawerIconScale(value: Float)
    fun setAppLabelColor(argb: Int)
    fun setTwoLineHomeLabels(value: Boolean)
    fun setTwoLineDrawerLabels(value: Boolean)
    fun setShowStatusBar(value: Boolean)
    fun setShowWeather(value: Boolean)
    fun setNetworkPlaceNames(value: Boolean)
    fun setWidgetTonalBackground(value: Boolean)
    fun setNotificationWidgetCountStyle(value: String)
    fun setPeoplePrivacy(value: String)
    fun setPeopleShowApps(value: Boolean)
    fun setPeopleBatchEnabled(value: Boolean)
    fun setPeopleBatchTimes(value: String)
    fun setHideSystemStatusBar(value: Boolean)
    fun setHideSystemNavigationBar(value: Boolean)
    fun setFolderShowLabels(value: Boolean)
    fun setFolderIconScale(value: Float)
    fun setFolderSpacing(value: Float)
    fun setFolderBackgroundColor(argb: Int?)
    fun setFolderBackgroundOpacity(value: Float)
    fun setSmartspaceBackgroundColor(argb: Int?)
    fun setSmartspaceBackgroundOpacity(value: Float)
    fun setSmartspaceTextScale(value: Float)
    fun setWeatherIconStyle(value: String)
    fun setWeatherIconLarge(value: Boolean)
    fun setHomeGlassPanel(value: Boolean)
    fun setHomeGlassOpacity(value: Float)
    fun setStatusBarScrimOpacity(value: Float)
}
